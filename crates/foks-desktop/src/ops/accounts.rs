//! Account enrollment, owner backup and owner recovery operations.

use foks_agent_proto::{Operation, SecretString};
use zeroize::Zeroizing;

use super::{
    bounded_field, bounded_local_name, bounded_secret, optional_bounded_field, InvalidInput,
};

pub const MAXIMUM_INVITE_BYTES: usize = 4 * 1024;
pub const MAXIMUM_PASSPHRASE_BYTES: usize = 1024;
pub const MAXIMUM_RECOVERY_PHRASE_BYTES: usize = 4 * 1024;
const MAXIMUM_EMAIL_BYTES: usize = 320;
const PROFILE_MESSAGE: &str = "Provide a valid server profile name.";

/// Input for a new account on `profile`. The passphrase, when present, has
/// already been confirmed with [`confirmed_passphrase`].
pub struct NewAccount<'a> {
    pub profile: &'a str,
    pub alias: &'a str,
    pub username: &'a str,
    pub device_name: &'a str,
    pub email: &'a str,
    /// Empty when the server needs no invitation.
    pub invite: &'a str,
    pub passphrase: Option<SecretString>,
}

/// Builds `CreateAccount`, applying the username and device name rules the
/// server enforces so a rejected value is named before any network request.
pub fn create_account_operation(account: NewAccount<'_>) -> Result<Operation, InvalidInput> {
    let profile = bounded_local_name(account.profile, PROFILE_MESSAGE)?;
    let alias = bounded_local_name(account.alias, "Enter a valid local account alias.")?;
    let username = valid_username(account.username)?;
    let device_name = valid_device_name(account.device_name)?;
    let email = optional_bounded_field(
        account.email,
        MAXIMUM_EMAIL_BYTES,
        "Enter a valid email address.",
    )?;
    let invite = Zeroizing::new(optional_bounded_field(
        account.invite,
        MAXIMUM_INVITE_BYTES,
        "Invitation code must be a single line of at most 4,096 bytes.",
    )?);
    Ok(Operation::CreateAccount {
        profile,
        alias,
        username,
        device_name,
        email,
        invite: SecretString::new(invite.as_str()),
        passphrase: account.passphrase,
    })
}

/// Builds `ResumeAccount` for a pending account signup.
pub fn resume_account_operation(profile: &str, alias: &str) -> Result<Operation, InvalidInput> {
    Ok(Operation::ResumeAccount {
        profile: bounded_local_name(profile, PROFILE_MESSAGE)?,
        alias: bounded_local_name(alias, "Choose a valid pending account alias.")?,
    })
}

/// Builds `PrepareOwnerBackup`, which generates a recovery phrase without
/// publishing it.
pub fn prepare_owner_backup_operation(
    profile: &str,
    account_alias: &str,
    backup_alias: &str,
) -> Result<Operation, InvalidInput> {
    Ok(Operation::PrepareOwnerBackup {
        profile: bounded_local_name(profile, PROFILE_MESSAGE)?,
        account_alias: bounded_local_name(account_alias, "Choose a valid account alias.")?,
        backup_alias: bounded_local_name(backup_alias, "Enter a valid backup alias.")?,
    })
}

/// Builds `CommitOwnerBackup` for the phrase a prior `PrepareOwnerBackup`
/// returned. The agent compares the phrase with the prepared one, so it is
/// only bounded here, not parsed.
pub fn commit_owner_backup_operation(
    profile: &str,
    account_alias: &str,
    backup_alias: &str,
    phrase: &str,
) -> Result<Operation, InvalidInput> {
    Ok(Operation::CommitOwnerBackup {
        profile: bounded_local_name(profile, PROFILE_MESSAGE)?,
        account_alias: bounded_local_name(account_alias, "Choose a valid account alias.")?,
        backup_alias: bounded_local_name(backup_alias, "Provide a valid backup alias.")?,
        phrase: bounded_secret(
            phrase,
            MAXIMUM_RECOVERY_PHRASE_BYTES,
            "Recovery phrase must be a single line of at most 4,096 bytes.",
        )?,
    })
}

/// Builds `RecoverOwnerAccount`. `serial` is the new device's positive random
/// serial, generated by the caller.
pub fn recover_owner_account_operation(
    profile: &str,
    target_alias: &str,
    phrase: &str,
    device_name: &str,
    serial: u64,
) -> Result<Operation, InvalidInput> {
    Ok(Operation::RecoverOwnerAccount {
        profile: bounded_local_name(profile, PROFILE_MESSAGE)?,
        target_alias: bounded_local_name(target_alias, "Enter a valid local account alias.")?,
        device_name: valid_device_name(device_name)?,
        phrase: recovery_phrase(phrase)?,
        serial,
    })
}

/// Builds `ResumeOwnerRecovery` for a pending recovery. The serial is the one
/// the agent retained with the pending record.
pub fn resume_owner_recovery_operation(
    profile: &str,
    target_alias: &str,
    phrase: &str,
    device_name: &str,
) -> Result<Operation, InvalidInput> {
    Ok(Operation::ResumeOwnerRecovery {
        profile: bounded_local_name(profile, PROFILE_MESSAGE)?,
        target_alias: bounded_local_name(target_alias, "Choose a valid pending recovery alias.")?,
        device_name: valid_device_name(device_name)?,
        phrase: recovery_phrase(phrase)?,
    })
}

/// A username the server will accept, checked here so a space or capital is
/// refused with a sentence instead of a normalization error from the client.
pub fn valid_username(value: &str) -> Result<String, InvalidInput> {
    let value = bounded_field(value, 256, "Enter a username.")?;
    if foks_verify::normalize_username(value.as_bytes()).is_none() {
        return Err(InvalidInput::new(
            "Usernames use 3 to 25 letters, numbers, and single underscores.",
        ));
    }
    Ok(value)
}

/// A device name the server will accept, by the same rules the client applies.
pub fn valid_device_name(value: &str) -> Result<String, InvalidInput> {
    if value.len() > foks_agent_proto::MAXIMUM_DEVICE_NAME_BYTES {
        return Err(InvalidInput::new(
            "Device name input cannot exceed 4,096 bytes.",
        ));
    }
    let value = foks_client::fix_device_name(value);
    if value.is_empty() {
        return Err(InvalidInput::new("Enter a device name."));
    }
    if value.chars().any(|c| {
        c.is_control()
            || matches!(c,
        '\u{00ad}' | '\u{061c}' | '\u{200b}'..='\u{200f}' |
        '\u{202a}'..='\u{202e}' | '\u{2060}'..='\u{206f}' | '\u{feff}')
    }) {
        return Err(InvalidInput::new(
            "Remove invisible formatting or control characters from the device name.",
        ));
    }
    if foks_verify::normalize_device_name(value.as_bytes()).is_none() {
        return Err(InvalidInput::new(foks_client::DEVICE_NAME_RULES));
    }
    Ok(value)
}

/// A recovery phrase, parsed before it leaves the app so a typo is named by
/// position rather than reported as a failed recovery.
pub fn recovery_phrase(value: &str) -> Result<SecretString, InvalidInput> {
    if value.is_empty() || value.len() > MAXIMUM_RECOVERY_PHRASE_BYTES || value.contains('\0') {
        return Err(InvalidInput::new(
            "Recovery phrase must contain at most 4,096 bytes and no null characters.",
        ));
    }
    if let Err(error) = foks_crypto::BackupKey::from_phrase(value) {
        use foks_crypto::RecoveryPhraseError as E;
        return Err(InvalidInput::new(match error {
            E::TokenCount { found } => format!(
                "A recovery phrase has {} words and numbers; this one has {found}.",
                foks_crypto::RECOVERY_PHRASE_TOKENS
            ),
            E::Word { index } => format!(
                "Word {} of the recovery phrase is not a recognized word. Check its spelling.",
                index + 1
            ),
            E::Number { index } | E::NumberRange { index } => format!(
                "Number {} of the recovery phrase should be a whole number from 0 to 8191.",
                index + 1
            ),
            _ => "That recovery phrase is not valid.".to_owned(),
        }));
    }
    Ok(SecretString::new(value))
}

/// A new passphrase typed twice. Both entries must match exactly and form one
/// nonempty line of at most [`MAXIMUM_PASSPHRASE_BYTES`].
pub fn confirmed_passphrase(
    passphrase: &str,
    confirmation: &str,
) -> Result<SecretString, InvalidInput> {
    if passphrase != confirmation {
        return Err(InvalidInput::new("Passphrase confirmation does not match."));
    }
    bounded_secret(
        passphrase,
        MAXIMUM_PASSPHRASE_BYTES,
        "A passphrase is required and cannot exceed 1,024 characters.",
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn new_account<'a>(username: &'a str, device_name: &'a str) -> NewAccount<'a> {
        NewAccount {
            profile: "work",
            alias: "personal",
            username,
            device_name,
            email: " sol@example.com ",
            invite: "",
            passphrase: None,
        }
    }

    fn message(result: Result<Operation, InvalidInput>) -> String {
        result.unwrap_err().message().to_owned()
    }

    #[test]
    fn create_account_applies_the_server_name_rules() {
        let Operation::CreateAccount {
            username,
            device_name,
            email,
            invite,
            ..
        } = create_account_operation(new_account("sol", "  Sol\u{2019}s   laptop ")).unwrap()
        else {
            panic!("expected CreateAccount");
        };
        assert_eq!(username, "sol");
        assert_eq!(device_name, "Sol's laptop");
        assert_eq!(email, "sol@example.com");
        assert_eq!(invite.expose(), "");

        assert_eq!(
            message(create_account_operation(new_account(
                "Sol Example",
                "laptop"
            ))),
            "Usernames use 3 to 25 letters, numbers, and single underscores."
        );
        assert_eq!(
            message(create_account_operation(new_account(
                "sol",
                "laptop\u{200b}"
            ))),
            "Remove invisible formatting or control characters from the device name."
        );
        assert_eq!(
            message(create_account_operation(NewAccount {
                alias: "personal account",
                ..new_account("sol", "laptop")
            })),
            "Enter a valid local account alias."
        );
        assert_eq!(
            message(create_account_operation(NewAccount {
                invite: "line one\nline two",
                ..new_account("sol", "laptop")
            })),
            "Invitation code must be a single line of at most 4,096 bytes."
        );
    }

    #[test]
    fn local_names_are_checked_before_any_operation_is_built() {
        assert_eq!(
            message(resume_account_operation("work/", "personal")),
            PROFILE_MESSAGE
        );
        assert_eq!(
            message(prepare_owner_backup_operation("work", "personal", " paper")),
            "Enter a valid backup alias."
        );
        assert_eq!(
            prepare_owner_backup_operation("work", "personal", "paper").unwrap(),
            Operation::PrepareOwnerBackup {
                profile: "work".to_owned(),
                account_alias: "personal".to_owned(),
                backup_alias: "paper".to_owned(),
            }
        );
    }

    #[test]
    fn recovery_names_a_malformed_phrase_and_backup_commit_only_bounds_it() {
        assert_eq!(
            message(recover_owner_account_operation(
                "work",
                "recovered",
                "abandon 0 abandon",
                "laptop",
                7
            )),
            "A recovery phrase has 17 words and numbers; this one has 3."
        );
        assert_eq!(
            message(resume_owner_recovery_operation(
                "work",
                "recovered",
                "",
                "laptop"
            )),
            "Recovery phrase must contain at most 4,096 bytes and no null characters."
        );
        assert!(commit_owner_backup_operation("work", "personal", "paper", "abandon 0").is_ok());
        assert_eq!(
            message(commit_owner_backup_operation(
                "work",
                "personal",
                "paper",
                "abandon\n0"
            )),
            "Recovery phrase must be a single line of at most 4,096 bytes."
        );
    }

    #[test]
    fn passphrases_must_match_and_fit_one_line() {
        assert_eq!(
            confirmed_passphrase("correct horse", "correct horse")
                .unwrap()
                .expose(),
            "correct horse"
        );
        assert_eq!(
            confirmed_passphrase("correct horse", "correct horse ")
                .unwrap_err()
                .message(),
            "Passphrase confirmation does not match."
        );
        let long = "a".repeat(MAXIMUM_PASSPHRASE_BYTES + 1);
        assert!(confirmed_passphrase(&long, &long).is_err());
        assert!(confirmed_passphrase("", "").is_err());
    }
}
